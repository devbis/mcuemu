#!/usr/bin/env python3
"""Assembles the test programs into ../programs.hpp (needs arm-none-eabi-as and
-objcopy). The generated header is committed so the tests build without the
toolchain; rerun this after editing a .s file."""
import os
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
names = sorted(f[:-2] for f in os.listdir(here) if f.endswith(".s"))
out = ["// Generated by programs/build.py from programs/*.s; do not edit.", "#pragma once", "",
       "#include <cstdint>", "#include <vector>", "", "namespace nrf52_programs {", ""]
for name in names:
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, name + ".o")
        binary = os.path.join(tmp, name + ".bin")
        subprocess.check_call(["arm-none-eabi-as", "-mcpu=cortex-m4", "-mfpu=fpv4-sp-d16",
                               "-mfloat-abi=hard", "-o", obj, os.path.join(here, name + ".s")])
        subprocess.check_call(["arm-none-eabi-objcopy", "-O", "binary", obj, binary])
        data = open(binary, "rb").read()
    out.append(f"inline const std::vector<std::uint8_t> {name} = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append("")
out.append("} // namespace nrf52_programs")
open(os.path.join(here, "..", "programs.hpp"), "w").write("\n".join(out) + "\n")
print("wrote programs.hpp:", ", ".join(names))
