#!/usr/bin/env python3
"""Assembles the test programs into ../programs.hpp (needs an LLVM with the
RISC-V target: clang, ld.lld and llvm-objcopy; set LLVM_BIN if they are not on
PATH, e.g. /opt/homebrew/opt/llvm/bin). The generated header is committed so the
tests build without the toolchain; rerun this after editing a .s file.
Images are linked at 0x42000000 (where the ESP32-C6/H2 map their flash) unless the
first line is "# base: 0x...", e.g. 0x40800000 for the SRAM."""
import os
import re
import shutil
import subprocess
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
llvm = os.environ.get("LLVM_BIN", "")


def tool(name):
    path = shutil.which(name, path=llvm or None) or shutil.which(name)
    if not path:
        raise SystemExit(f"{name} not found; set LLVM_BIN")
    return path


names = sorted(f[:-2] for f in os.listdir(here) if f.endswith(".s"))
out = ["// Generated by programs/build.py from programs/*.s; do not edit.", "#pragma once", "",
       "#include <cstdint>", "#include <vector>", "", "namespace riscv_programs {", ""]
for name in names:
    first = open(os.path.join(here, name + ".s")).readline()
    base = re.match(r"#\s*base:\s*(0x[0-9a-fA-F]+)", first)
    base = base.group(1) if base else "0x42000000"
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, name + ".o")
        elf = os.path.join(tmp, name + ".elf")
        binary = os.path.join(tmp, name + ".bin")
        subprocess.check_call([tool("clang"), "--target=riscv32", "-march=rv32imac_zicsr",
                               "-mabi=ilp32", "-c", os.path.join(here, name + ".s"), "-o", obj])
        subprocess.check_call([tool("ld.lld"), "-m", "elf32lriscv", "-Ttext=" + base, obj,
                               "-o", elf])
        subprocess.check_call([tool("llvm-objcopy"), "-O", "binary", elf, binary])
        data = open(binary, "rb").read()
    out.append(f"inline const std::vector<std::uint8_t> {name} = {{")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append("")
out.append("} // namespace riscv_programs")
open(os.path.join(here, "..", "programs.hpp"), "w").write("\n".join(out) + "\n")
print("wrote programs.hpp:", ", ".join(names))
