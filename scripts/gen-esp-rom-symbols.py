#!/usr/bin/env python3
"""Generates the ROM symbol table of an ESP32 chip from the linker scripts of
esp-rom-sys (esp-rs/esp-hal, esp-rom-sys/ld/<chip>/rom/*.ld) or ESP-IDF
(components/esp_rom/<chip>/ld/*.ld).

The emulator has no ROM image; it replaces the ROM functions firmware calls by
host code. The table maps address to name, so a replacement is registered by name
and an unhandled call is logged with its name.

Usage: gen-esp-rom-symbols.py --chip esp32c6 --out emulator/include/esp32emu/esp32c6_rom.hpp LD...
"""
import argparse
import re
import sys

LINE = re.compile(r"^\s*(?:PROVIDE\s*\(\s*)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0x[0-9a-fA-F]+)\s*\)?\s*;")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chip", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("ld", nargs="+")
    a = ap.parse_args()
    symbols = {}
    for path in a.ld:
        for line in open(path):
            m = LINE.match(line)
            if m:
                symbols[m.group(1)] = int(m.group(2), 16)
    rows = sorted(symbols.items(), key=lambda kv: (kv[1], kv[0]))
    with open(a.out, "w") as f:
        f.write("// Generated by scripts/gen-esp-rom-symbols.py from the %s ROM linker scripts.\n"
                "// Do not edit.\n#pragma once\n\n#include <cstdint>\n\n"
                "namespace esp32emu::%s_rom {\n\n"
                "struct Symbol {\n    std::uint32_t address;\n    const char *name;\n};\n\n"
                "inline constexpr Symbol symbols[] = {\n" % (a.chip, a.chip))
        for name, addr in rows:
            f.write('    {0x%08x, "%s"},\n' % (addr, name))
        f.write("};\n\n} // namespace esp32emu::%s_rom\n" % a.chip)
    print("%d symbols" % len(rows), file=sys.stderr)


if __name__ == "__main__":
    main()
