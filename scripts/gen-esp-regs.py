#!/usr/bin/env python3
"""Generates register headers for the ESP32-C6 / ESP32-H2 models from SVD files.

The SVD files come from https://github.com/esp-rs/esp-pacs (esp32c6/svd,
esp32h2/svd). They describe the layout (base addresses, offsets, fields, reset
values, interrupt source numbers) and nothing about behaviour: which bits
self-clear or what an operation takes has to come from the TRM and from driver
code (esp-hal, ESP-IDF).

Usage:
  gen-esp-regs.py --svd esp32c6.base.svd --chip esp32c6 --out esp32c6_regs.hpp \
      [--peripheral NAME ...]

Without --peripheral every peripheral in DEFAULT_PERIPHERALS that exists in
the file is emitted. Output: one namespace per peripheral with `base`, a
`reg::NAME` offset, `reset::NAME` value and `NAME_FIELD_shift/width` constants,
plus an `irq` table of interrupt source numbers.
"""
import argparse
import sys
import xml.etree.ElementTree as ET

DEFAULT_PERIPHERALS = [
    "IEEE802154", "UART0", "UART1", "GPIO", "IO_MUX", "SYSTIMER", "TIMG0",
    "TIMG1", "INTPRI", "INTERRUPT_CORE0", "PCR", "PMU", "EFUSE",
    "MODEM_LPCON", "MODEM_SYSCON", "LP_CLKRST", "LP_WDT", "LP_AON", "SPI0", "SPI1",
    "LP_I2C_ANA_MST", "LP_TIMER",
]


def num(text):
    return int(text.strip(), 0)


def find_periph(root, name):
    for p in root.iter("peripheral"):
        if p.findtext("name") == name:
            return p
    return None


def expand_dim(reg):
    """Yields (name, offset) for a register or a dim array of registers."""
    name = reg.findtext("name")
    off = num(reg.findtext("addressOffset"))
    dim = reg.findtext("dim")
    if dim is None:
        # The base SVD is unpatched. A "%s" left in a name without a dim is a
        # template for timer 0 (esp-pacs/esp32*/svd/patches/_timg.yml renames
        # T%sCONFIG to T0CONFIG).
        yield name.replace("%s", "0"), off
        return
    inc = num(reg.findtext("dimIncrement"))
    idx = reg.findtext("dimIndex")
    labels = idx.split(",") if idx else [str(i) for i in range(num(dim))]
    for i, label in enumerate(labels):
        yield name.replace("%s", label.strip()).replace("[%s]", label.strip()), off + i * inc


def registers(node, prefix=""):
    for child in node:
        if child.tag == "register":
            for name, off in expand_dim(child):
                yield prefix + name, off, child
        elif child.tag == "cluster":
            coff = num(child.findtext("addressOffset"))
            for cname, base in expand_dim(child):
                for name, off, reg in registers(child, prefix + cname + "_"):
                    yield name, base - coff + off, reg


def fields(reg):
    for f in reg.iter("field"):
        name = f.findtext("name")
        if "bitOffset" in f.keys() or f.findtext("bitOffset") is not None:
            shift = num(f.findtext("bitOffset"))
            width = num(f.findtext("bitWidth"))
        else:  # bitRange "[msb:lsb]"
            msb, lsb = f.findtext("bitRange").strip("[]").split(":")
            shift, width = int(lsb), int(msb) - int(lsb) + 1
        yield name, shift, width


def emit(root, chip, names, out):
    out.write("// Generated by scripts/gen-esp-regs.py from the %s SVD (esp-rs/esp-pacs).\n"
              "// Do not edit. Layout only: behaviour is in the register models.\n"
              "#pragma once\n\n#include <cstdint>\n\n"
              "// <windows.h> defines IN and OUT as empty macros; register names (GPIO IN/OUT) must survive it; the\n"
              "// project never needs the SAL meaning, so they stay undefined.\n"
              "#undef IN\n#undef OUT\n\n"
              "namespace %s_regs {\n\n" % (chip, chip))
    for name in names:
        p = find_periph(root, name)
        if p is None:
            print("warning: %s not in the SVD" % name, file=sys.stderr)
            continue
        src = p
        if p.get("derivedFrom"):
            src = find_periph(root, p.get("derivedFrom"))
        out.write("namespace %s {\n" % name.lower())
        out.write("inline constexpr std::uint32_t base = %s;\n" % p.findtext("baseAddress"))
        ab = src.find("addressBlock")
        if ab is not None:
            out.write("inline constexpr std::uint32_t size = %s;\n" % ab.findtext("size"))
        regs = list(registers(src.find("registers")))
        out.write("namespace reg {\n")
        for rname, off, _ in regs:
            out.write("inline constexpr std::uint32_t %s = 0x%x;\n" % (rname, off))
        out.write("} // namespace reg\nnamespace reset {\n")
        for rname, _, r in regs:
            rv = r.findtext("resetValue")
            out.write("inline constexpr std::uint32_t %s = %s;\n" % (rname, rv if rv else "0"))
        out.write("} // namespace reset\n")
        out.write("namespace field {\n")
        for rname, _, r in regs:
            for fname, shift, width in fields(r):
                out.write("inline constexpr unsigned %s_%s_shift = %d;\n" % (rname, fname, shift))
                out.write("inline constexpr unsigned %s_%s_width = %d;\n" % (rname, fname, width))
        out.write("} // namespace field\n")
        irqs = [(i.findtext("name"), num(i.findtext("value"))) for i in p.findall("interrupt")]
        if irqs:
            out.write("namespace irq {\n")
            for iname, val in irqs:
                out.write("inline constexpr unsigned %s = %d;\n" % (iname, val))
            out.write("} // namespace irq\n")
        out.write("} // namespace %s\n\n" % name.lower())
    out.write("} // namespace %s_regs\n" % chip)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--svd", required=True)
    ap.add_argument("--chip", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--peripheral", action="append")
    a = ap.parse_args()
    root = ET.parse(a.svd).getroot()
    names = a.peripheral or DEFAULT_PERIPHERALS
    with open(a.out, "w") as f:
        emit(root, a.chip, names, f)


if __name__ == "__main__":
    main()
